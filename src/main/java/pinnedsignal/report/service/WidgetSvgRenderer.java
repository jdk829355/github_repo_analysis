package pinnedsignal.report.service;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.stream.Collectors;
import pinnedsignal.global.util.TextUtils;
import pinnedsignal.report.entity.RoleEstimation;

/**
 * services/widget-export.ts를 옮긴 것. README에 붙는 SVG라서 Node 앱이 만든 것과 바이트까지 같아야 한다.
 * 줄 나누기는 JS 문자열 길이(UTF-16 코드 유닛)와 JS 공백 기준을 따른다.
 */
public final class WidgetSvgRenderer {

    public static final String VERSION = "inner-card-v4";

    private static final String FONT = "font-family=\"Inter, Arial, sans-serif\"";
    private static final String FALLBACK_FLAG = "분석 신호가 아직 충분하지 않습니다.";

    public enum Theme { LIGHT, DARK }

    public record Variants(String light, String dark) {
    }

    /** repositoryLanguages는 pinned 저장소마다 하나다. 언어를 모르면 빈 문자열이다. */
    public record WidgetReport(
            String githubUsername,
            String overallSummary,
            RoleEstimation roleEstimation,
            List<String> greenFlags,
            List<String> redFlags,
            List<String> repositoryLanguages) {
    }

    private record Colors(String card, String border, String heading, String body, String muted, String brand,
            String brandText, String accentHeading, String marker) {
    }

    private static final Colors LIGHT = new Colors(
            "#FFFFFF", "#D9DEEA", "#181C22", "#414753", "#717785", "#005AB4", "#FFFFFF", "#005AB4", "#58A6FF");
    private static final Colors DARK = new Colors(
            "#0D1117", "#30363D", "#F4F7FB", "#D5DCE7", "#9AA6B6", "#58A6FF", "#07111F", "#58A6FF", "#58A6FF");

    private WidgetSvgRenderer() {
    }

    public static Variants renderVariants(WidgetReport report) {
        return new Variants(render(report, Theme.LIGHT), render(report, Theme.DARK));
    }

    public static String render(WidgetReport report, Theme theme) {
        Colors colors = theme == Theme.DARK ? DARK : LIGHT;
        String primary = report.roleEstimation().primary();
        String primaryRole = primary == null || primary.isEmpty() ? "Developer" : primary;
        int roleWidth = Math.max(112, primaryRole.length() * 10 + 34);
        String profileTitle = report.githubUsername() != null && !report.githubUsername().isEmpty()
                ? "@ " + report.githubUsername() : "GitHub Profile";
        String techStack = topTechStack(report.repositoryLanguages());
        List<String> summaryLines = toLines(report.overallSummary(), 70, 3);

        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <svg width="613" height="431" viewBox="0 0 876 616" fill="none" xmlns="http://www.w3.org/2000/svg" role="img" aria-labelledby="title desc" data-widget-version="%s">
                  <title id="title">Pinned Signal GitHub profile analysis widget</title>
                  <desc id="desc">A GitHub profile analysis summary with green flags and growth areas.</desc>
                  <rect x="0.5" y="0.5" width="875" height="615" rx="22" fill="%s" stroke="%s"/>
                  <text x="36" y="46" %s font-size="13" font-weight="800" letter-spacing="1.5" fill="%s">PINNED SIGNAL</text>
                  <text x="36" y="90" %s font-size="34" font-weight="800" fill="%s">%s</text>
                  <rect x="692" y="36" width="126" height="34" rx="17" fill="%s"/>
                  <text x="755" y="58" text-anchor="middle" %s font-size="13" font-weight="800" fill="%s">%d pinned repos</text>
                  <g %s>
                    %s
                  </g>
                  <rect x="36" y="210" width="%d" height="36" rx="18" fill="%s"/>
                  <text x="%d" y="233" text-anchor="middle" %s font-size="14" font-weight="800" fill="%s">%s</text>
                  <text x="%d" y="233" %s font-size="14" font-weight="700" fill="%s">%s</text>
                  <text x="60" y="332" %s font-size="22" font-weight="800" fill="%s">Green Flags</text>
                  <g %s>
                    %s
                  </g>
                  <text x="482" y="332" %s font-size="22" font-weight="800" fill="%s">Growth Areas</text>
                  <g %s>
                    %s
                  </g>
                  <text x="36" y="590" %s font-size="12" font-weight="700" fill="%s">Generated by Pinned Signal</text>
                </svg>""".formatted(
                VERSION,
                colors.card(), colors.border(),
                FONT, colors.brand(),
                FONT, colors.heading(), escapeXml(profileTitle),
                colors.brand(),
                FONT, colors.brandText(), report.repositoryLanguages().size(),
                FONT,
                renderTextLines(summaryLines, 36, 132, 15, colors.body(), 24),
                roleWidth, colors.brand(),
                36 + roleWidth / 2, FONT, colors.brandText(), escapeXml(primaryRole),
                36 + roleWidth + 20, FONT, colors.muted(), escapeXml(techStack),
                FONT, colors.accentHeading(),
                FONT,
                renderFlagItems(report.greenFlags(), 64, 370, colors),
                FONT, colors.accentHeading(),
                FONT,
                renderFlagItems(report.redFlags(), 486, 370, colors),
                FONT, colors.muted());
    }

    static String escapeXml(String value) {
        return value
                .replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&apos;");
    }

    private static String topTechStack(List<String> languages) {
        return languages.stream()
                .filter(language -> language != null && !language.isEmpty())
                .collect(Collectors.toCollection(LinkedHashSet::new))
                .stream()
                .limit(4)
                .collect(Collectors.joining(" · "));
    }

    private static List<String> splitLineByLength(String value, int maxLength) {
        List<String> lines = new ArrayList<>();
        String current = "";

        for (String word : TextUtils.splitWords(value)) {
            if (word.length() > maxLength) {
                if (!current.isEmpty()) {
                    lines.add(current);
                    current = "";
                }
                for (int index = 0; index < word.length(); index += maxLength) {
                    lines.add(word.substring(index, Math.min(index + maxLength, word.length())));
                }
                continue;
            }

            String next = current.isEmpty() ? word : current + " " + word;
            if (next.length() > maxLength && !current.isEmpty()) {
                lines.add(current);
                current = word;
            } else {
                current = next;
            }
        }

        if (!current.isEmpty()) {
            lines.add(current);
        }
        return lines;
    }

    private static List<String> toLines(String value, int maxLength, int maxLines) {
        List<String> allLines = splitLineByLength(TextUtils.collapseWhitespace(value), maxLength);
        List<String> lines = new ArrayList<>(allLines.subList(0, Math.min(maxLines, allLines.size())));

        if (lines.size() == maxLines && allLines.size() > maxLines) {
            String last = lines.get(maxLines - 1).replaceFirst("[.。]\\z", "");
            lines.set(maxLines - 1, last + "...");
        }
        return lines;
    }

    private static String renderTextLines(List<String> lines, int x, int y, int size, String fill, int lineHeight) {
        StringBuilder svg = new StringBuilder();
        for (int index = 0; index < lines.size(); index++) {
            svg.append("<text x=\"").append(x)
                    .append("\" y=\"").append(y + index * lineHeight)
                    .append("\" font-size=\"").append(size)
                    .append("\" font-weight=\"400\" fill=\"").append(fill)
                    .append("\">").append(escapeXml(lines.get(index))).append("</text>");
        }
        return svg.toString();
    }

    private static String renderFlagItems(List<String> items, int x, int y, Colors colors) {
        List<String> visibleItems = (items == null || items.isEmpty() ? List.of(FALLBACK_FLAG) : items)
                .stream().limit(3).toList();

        StringBuilder svg = new StringBuilder();
        for (int itemIndex = 0; itemIndex < visibleItems.size(); itemIndex++) {
            int itemY = y + itemIndex * 58;
            svg.append("<circle cx=\"").append(x).append("\" cy=\"").append(itemY - 4)
                    .append("\" r=\"4\" fill=\"").append(colors.marker()).append("\" />");
            svg.append(renderTextLines(toLines(visibleItems.get(itemIndex), 30, 2), x + 16, itemY, 14, colors.body(), 19));
        }
        return svg.toString();
    }
}
